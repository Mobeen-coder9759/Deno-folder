CREATE TABLE clinics (
  id serial PRIMARY KEY,
  name varchar(150) NOT NULL,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE app_users (
  id serial PRIMARY KEY,
  username varchar(50) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  name varchar(100) NOT NULL,
  role varchar(20) NOT NULL CHECK (role::text = ANY (ARRAY['admin','staff','hr']::text[])),
  is_active boolean DEFAULT true,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  clinic_id integer REFERENCES clinics(id)
);
CREATE TABLE appointments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calendar_event_id varchar(255) NOT NULL UNIQUE,
  "timestamp" timestamptz DEFAULT CURRENT_TIMESTAMP,
  name varchar(150) NOT NULL,
  email varchar(255),
  dob date,
  insurance varchar(150),
  reason text,
  booking_type varchar(50),
  old_time timestamptz,
  booking_time timestamptz,
  cancel_time timestamptz,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  phone varchar(30),
  clinic_id integer REFERENCES clinics(id)
);
CREATE INDEX idx_appointments_phone ON appointments(phone);
